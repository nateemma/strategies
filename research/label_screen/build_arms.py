"""Build the label-screen classes and plans (034 T004; one-off generator; contract C1).

Per candidate (research/label_screen/candidates.py):

  * `NNNC/NNNC_LS_<TAG>.py`    = LabelParamsMixin + the control's base class, with TRAINING_TYPE,
                                 LABEL_PARAMS, LABEL_PARAMS_SELL and a 4-decimal threshold
                                 (entry-source role; also the training class);
  * `NNNC/NNNC_LS_<TAG>_SZ.py` = WidthSizerMixin + WidthBookMixin + NNNC_LS_<TAG>, with the width
                                 book's WIDTH_CUTS (sizer role; same model key);
  * GFM reuses `NNNC_GbbFwdMae_Open` (no label mixin) so its existing weights are found by key.

Plans `evaluation/folds/plan_<ls tag>_{es,sz}.json` are copied from the control plan: same folds,
config and the control's 24 h-grace params snapshot (GFM's own snapshot differs only in grace);
new classes, model dirs and arm tags; no thresholds (picked after training).

    PYTHONPATH=. ../../.venv/bin/python -m research.label_screen.build_arms [--model ARO]
"""

from __future__ import annotations

import argparse
import copy
import json
import sys
from pathlib import Path


STRAT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(STRAT))

from research.label_screen import candidates as C  # noqa: E402


FOLDS = STRAT / "evaluation" / "folds"
NNNC = STRAT / "NNNC"
CONTROLS = {"ARO": "wf_aro_g24", "GBR": "fs_gbr_gr"}
GFM_BASE = "NNNC_GbbFwdMae_Open"

HEAD = '''# pragma pylint: disable=C0103, C0114, C0115, C0116, C0301
# type: ignore
"""{doc}"""

import sys
from pathlib import Path


sys.path.append(str(Path(__file__).parent))
sys.path.append(str(Path(__file__).parent.parent))

'''

LABEL_TMPL = HEAD + '''from freqtrade.strategy import DecimalParameter
from LabelParamsMixin import LabelParamsMixin
from {base} import {base}


class {name}(LabelParamsMixin, {base}):
    # pinned to the control's resolved family: the 029 label-driven family would tag outcome-only
    # labels' entries as no family and breakout_gbb's as momentum (held-pair add off), a second
    # variable (research R3 amendment)
    MODEL_ENTRY_FAMILY = "reversion"
    TRAINING_TYPE = {method}
    LABEL_PARAMS = {params!r}
    LABEL_PARAMS_SELL = {sell!r}
    prediction_threshold = DecimalParameter(0.0, 1.0, default=0.5, decimals=4, space="buy",
                                            load=True, optimize=False)
'''

GFM_TMPL = HEAD + '''from freqtrade.strategy import DecimalParameter
from {base} import {base}


class {name}({base}):
    prediction_threshold = DecimalParameter(0.0, 1.0, default=0.5, decimals=4, space="buy",
                                            load=True, optimize=False)
'''

SZ_TMPL = HEAD + '''from _width_book import WidthBookMixin
from _width_sizer import WidthSizerMixin
from {label} import {label}


class {name}(WidthSizerMixin, WidthBookMixin, {label}):
    WIDTH_CUTS = {cuts}
'''


def width_cuts(model: str) -> dict:
    sys.path[:0] = [str(STRAT), str(NNNC)]
    from evaluation.fingerprint import load_strategy_class

    return dict(load_strategy_class(f"NNNC_W_{model}").WIDTH_CUTS)


def _write_class(name: str, src: str, base_json: str) -> None:
    (NNNC / f"{name}.py").write_text(src)
    bj = json.loads((NNNC / f"{base_json}.json").read_text())
    bj["strategy_name"] = name
    (NNNC / f"{name}.json").write_text(json.dumps(bj, indent=4) + "\n")


def _plan(ctl_plan: dict, c: C.Candidate, role: str, cls: str, model: str) -> dict:
    new = copy.deepcopy(ctl_plan)
    tag = C.plan_tag(c, role, model)
    label = C.class_name(c, model)
    new["run_id"], new["base_strategy"] = tag, cls
    new.pop("thresholds", None)
    for f in new["folds"]:
        f["strategy_class"] = f"{label}_{role.upper()}_{f['fold_id']}"
        f["model_dir"] = f"user_data/strategies/saved_data/{label}_{f['fold_id']}"
        f["arm_tag"] = f"{tag}_{f['fold_id']}"
        f["status"] = "planned"
    new["ls_note"] = (f"034 label screen: {c.tag} (LabelMethod {c.method}) as "
                      f"{'width-book sizer' if role == 'sz' else 'ungated entry source'}; control "
                      f"{CONTROLS[model]}; thresholds picked after training "
                      f"(research/label_screen/pick.py)")
    return new


def build(model: str = "ARO", tags: tuple | None = None) -> dict:
    ctl = CONTROLS[model]
    ctl_plan = json.loads((FOLDS / f"plan_{ctl}.json").read_text())
    base = ctl_plan["base_strategy"]
    cuts = width_cuts(model)
    body = "{\n" + "".join(f"        {k!r}: {v!r},\n" for k, v in cuts.items()) + "    }"
    out = {}
    for c in C.CANDIDATES:
        if c.tag == "CONTROL" or (tags and c.tag not in tags) or (model != "ARO" and c.tag == "GFM"):
            continue
        label = C.class_name(c, model)
        doc = (f"034 label screen ({model}; GENERATED by research/label_screen/build_arms.py): "
               f"{c.tag}, LabelMethod {c.method}. Everything else is `{base}` (control `{ctl}`).")
        if c.tag == "GFM":
            _write_class(label, GFM_TMPL.format(doc=doc, base=GFM_BASE, name=label), GFM_BASE)
        else:
            _write_class(label, LABEL_TMPL.format(doc=doc, base=base, name=label, method=c.method,
                                                  params=c.label_params,
                                                  sell=c.label_params_sell), base)
        sz = f"{label}_SZ"
        _write_class(sz, SZ_TMPL.format(doc=doc + " Width-book sizer.", label=label, name=sz,
                                        cuts=body), GFM_BASE if c.tag == "GFM" else base)
        for role in c.roles:
            p = _plan(ctl_plan, c, role, sz if role == "sz" else label, model)
            (FOLDS / f"plan_{p['run_id']}.json").write_text(json.dumps(p, indent=1) + "\n")
            out[p["run_id"]] = p["base_strategy"]
        if "es" not in c.roles:  # BOG: training still runs through an es-shaped plan
            p = _plan(ctl_plan, c, "es", label, model)
            p["ls_note"] += "; TRAINING ONLY (sizer-only candidate, never backtested as entry source)"
            (FOLDS / f"plan_{p['run_id']}.json").write_text(json.dumps(p, indent=1) + "\n")
            out[p["run_id"]] = p["base_strategy"]
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", choices=sorted(CONTROLS), default="ARO")
    ap.add_argument("--tags", help="comma-separated candidate tags (default all)")
    a = ap.parse_args()
    for k, v in build(a.model, tuple(a.tags.split(",")) if a.tags else None).items():
        print(k, v)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
