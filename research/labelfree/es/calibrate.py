"""THE BLOCKING GATE: does the surrogate RANK candidates the way real backtests do? (T023-T027)

Until this passes, no search result is admissible (SC-017). The surrogate re-implements
freqtrade's exit stack, duplication drifts, and this study has paid for drift repeatedly -- a
loss term that silently never ran, a purge landing in an already-discarded tail, four inert
parameters. An uncalibrated surrogate does not merely risk a wrong answer: the entire search
budget would optimise a fiction.

RANK, NOT LEVEL (research.md R4). The search only ever uses the surrogate to ORDER candidates.
A constant offset in level is harmless; a reordering is fatal. Demanding level agreement is
what failed in feature 012, where the "bit-for-bit" gate tripped on an MLX-vs-numpy log()
difference of ~5 ulps that no change could fix.

THE GATE: if the two orderings disagree on which candidate WINS, the search is optimising the
wrong thing and no result is admissible (SC-017a).

HOW A CANDIDATE IS BACKTESTED. A generated subclass of the fold's own strategy, which
  * overrides get_model_path() to the PARENT's — so it loads the fold's existing weights.
    Without this the new class name would give it an empty saved_data/ directory and it would
    TRAIN INSIDE ITS OWN BACKTEST, which is the trap NNNC_WF_*.py's docstring warns about.
  * carries its own <Strategy>.json, because that file overrides buy_params/sell_params.
  * sets the ATR constants as plain class attributes, which is what they are.
  * mixes in HoldWindowMixin for hold_window_hours.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
REPO = ROOT.parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from research.labelfree.es import evaluate as EV         # noqa: E402
from research.labelfree.es import panel as PA            # noqa: E402
from research.labelfree.es import space as SP            # noqa: E402

CONFIG = "user_data/strategies/config/config_wf.json"
STRAT_DIR = ROOT / "NNNC"
LOG_ROOT = Path("/tmp/lf/es_calib")
OUT = Path(__file__).resolve().parent / "calibration.json"

JSON_KEYS_SELL = ("cexit_take_profit", "cexit_max_days",
                  "stoploss_grace_hours", "stoploss_grace_level")
JSON_KEYS_BUY = ("entry_rvol_threshold", "entry_guard_threshold")
CLASS_ATTRS = ("atr_stoploss_multiplier", "atr_stoploss_floor", "atr_stoploss_cap")

TEMPLATE = '''# type: ignore
"""GENERATED by research/labelfree/es/calibrate.py — a calibration candidate. Do not edit.

Transient: written, backtested and deleted. Inherits {parent} and overrides get_model_path so
it loads THAT fold's weights; a class with no model of its own would train inside its own
backtest.
"""
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).parent))
sys.path.append(str(Path(__file__).parent.parent))

from _hold_window import HoldWindowMixin
from {parent} import {parent}


class {name}(HoldWindowMixin, {parent}):
    HOLD_WINDOW_HOURS = {hold_window_hours!r}
{attrs}

    def get_model_path(self) -> str:
        root = self.get_storage_location()
        return root + "{parent}/" + "{parent}.keras"
'''


def _write_candidate(fold_id: str, idx: int, params: dict) -> str:
    parent = f"NNNC_WF_{fold_id}"
    name = f"NNNC_ES_{fold_id}_c{idx:03d}"
    attrs = "\n".join(f"    {k} = {float(params[k])!r}" for k in CLASS_ATTRS)
    (STRAT_DIR / f"{name}.py").write_text(TEMPLATE.format(
        parent=parent, name=name, attrs=attrs,
        hold_window_hours=float(params["hold_window_hours"])))

    base = json.loads((STRAT_DIR / f"{parent}.json").read_text())
    p = base["params"]
    for k in JSON_KEYS_SELL:
        p.setdefault("sell", {})[k] = (int(params[k]) if k == "cexit_max_days"
                                       else float(params[k]))
    for k in JSON_KEYS_BUY:
        p.setdefault("buy", {})[k] = float(params[k])
    base["strategy_name"] = name
    (STRAT_DIR / f"{name}.json").write_text(json.dumps(base, indent=2))
    return name


def _cleanup(name: str) -> None:
    for suffix in (".py", ".json"):
        (STRAT_DIR / f"{name}{suffix}").unlink(missing_ok=True)
    import shutil
    shutil.rmtree(ROOT / "saved_data" / name, ignore_errors=True)


def _backtest(name: str, fold, log_root: Path = LOG_ROOT) -> float | None:
    """Annualised return in pp over the fold's TRAINING range. None if the run produced
    nothing — freqtrade exits 0 on a fatal config error, so freshness is the only signal."""
    log_root.mkdir(parents=True, exist_ok=True)
    log = log_root / f"{name}.log"
    tr = (f"{fold.train_start.replace('-', '')}-{fold.train_end.replace('-', '')}")
    started = time.time()
    cmd = ("[ -f \"$HOME/.freqtrade_env\" ] && . \"$HOME/.freqtrade_env\"; "
           f"cd {REPO} && PYTHONPATH=user_data/strategies .venv/bin/freqtrade backtesting "
           f"--strategy {name} --strategy-path user_data/strategies/NNNC "
           f"--config {CONFIG} --timerange {tr} --cache none")
    with log.open("w") as fh:
        fh.write(cmd + "\n\n")
        fh.flush()
        subprocess.run(["zsh", "-c", cmd], stdout=fh, stderr=fh)

    results = REPO / "user_data/backtest_results"
    latest = results / ".last_result.json"
    if not latest.exists():
        return None
    zp = results / json.loads(latest.read_text())["latest_backtest"]
    if not zp.exists() or zp.stat().st_mtime < started:
        return None                       # STALE: the run produced nothing. See the log.

    from research.labelfree import archive as A
    tr_df = A.load_trades(zp, strategy=name)
    if tr_df is None or len(tr_df) == 0:
        return 0.0
    import pandas as pd
    years = ((pd.Timestamp(fold.train_end) - pd.Timestamp(fold.train_start)).days / 365.25)
    equity = float(np.prod(1.0 + tr_df["profit_ratio"].to_numpy()))
    if equity <= 0 or years <= 0:
        return -100.0
    return (equity ** (1.0 / years) - 1.0) * 100.0


def sample(n: int, seed: int = 7) -> list[dict]:
    """Candidates SPANNING the space, not clustered near the incumbent.

    A sample hugging the incumbent would report a flattering rank correlation over a range the
    search will not stay inside.
    """
    rng = np.random.default_rng(seed)
    out = [dict(SP.INCUMBENT)]
    while len(out) < n:
        p = {d.name: (int(rng.integers(d.lo, d.hi + 1)) if d.integer
                      else float(rng.uniform(d.lo, d.hi))) for d in SP.DIMS}
        try:
            SP.validate(p)
        except SP.Inadmissible:
            continue
        out.append(p)
    return out


def run(n: int, fold_ids: list[str], seed: int = 7) -> dict:
    from research.labelfree.folds import folds
    by_id = {f.fold_id: f for f in folds()}
    fold = by_id[fold_ids[0]]                      # calibrate on ONE fold; ranks, not levels
    panel = PA.load(fold.fold_id, train=True)
    inc_tpy = EV.incumbent_trades_per_year(panel)

    cands = sample(n, seed)
    rows = []
    for i, p in enumerate(cands):
        s = EV.score(panel, p, inc_tpy)
        name = _write_candidate(fold.fold_id, i, p)
        try:
            bt = _backtest(name, fold)
        finally:
            _cleanup(name)
        rows.append({"idx": i, "params": p,
                     "surrogate": None if not np.isfinite(s.value) else s.unregularised,
                     "backtest": bt, "surrogate_trades": s.n_trades,
                     "admissible": s.admissible})
        print(f"  [{i + 1}/{n}] surrogate {rows[-1]['surrogate']!s:>8.8} "
              f"backtest {bt!s:>8.8}", flush=True)

    ok = [r for r in rows if r["surrogate"] is not None and r["backtest"] is not None]
    if len(ok) < 5:
        return {"passed": False, "verdict": "TOO FEW COMPARABLE CANDIDATES",
                "n_compared": len(ok), "rows": rows}

    from scipy.stats import spearmanr, kendalltau
    a = np.array([r["surrogate"] for r in ok])
    b = np.array([r["backtest"] for r in ok])
    rho = float(spearmanr(a, b).statistic)
    tau = float(kendalltau(a, b).statistic)

    win_s, win_b = int(np.argmax(a)), int(np.argmax(b))
    agree_on_winner = win_s == win_b
    disagreements = [
        {"i": ok[i]["idx"], "j": ok[j]["idx"],
         "surrogate": [round(a[i], 3), round(a[j], 3)],
         "backtest": [round(b[i], 3), round(b[j], 3)]}
        for i in range(len(ok)) for j in range(i + 1, len(ok))
        if np.sign(a[i] - a[j]) != np.sign(b[i] - b[j])]

    passed = agree_on_winner and rho > 0.5
    return {"passed": passed,
            "verdict": ("rank agreement sufficient" if passed else
                        ("the two orderings disagree on WHICH CANDIDATE WINS — the search "
                         "would optimise the wrong thing" if not agree_on_winner
                         else f"rank correlation {rho:.3f} too low to order candidates")),
            "spearman_rho": round(rho, 4), "kendall_tau": round(tau, 4),
            "agree_on_winner": agree_on_winner,
            "winner_surrogate": ok[win_s]["idx"], "winner_backtest": ok[win_b]["idx"],
            "n_compared": len(ok), "n_pair_disagreements": len(disagreements),
            "pair_disagreements": disagreements[:20],
            "fold": fold.fold_id, "rows": rows}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--n", type=int, default=40)
    ap.add_argument("--folds", default="f07")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()

    from research.labelfree.baselines import parse_span
    t0 = time.time()
    rep = run(a.n, parse_span(a.folds), a.seed)
    Path(a.out).write_text(json.dumps(rep, indent=2))

    print(f"\n{'PASSED' if rep['passed'] else 'FAILED'}: {rep['verdict']}")
    if "spearman_rho" in rep:
        print(f"  spearman rho      {rep['spearman_rho']:+.4f}   over {rep['n_compared']}"
              f" candidates")
        print(f"  kendall tau       {rep['kendall_tau']:+.4f}")
        print(f"  agree on winner   {rep['agree_on_winner']}")
        print(f"  pair disagreements {rep['n_pair_disagreements']}")
    print(f"\n{(time.time() - t0) / 60:.1f} min -> {a.out}")
    return 0 if rep["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
