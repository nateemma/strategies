"""Build the 031 held-pair add (DCA) arms from their controls (one-off generator).

For each book: an arm class `<prefix>_DCA` subclassing the CONTROL plan's base strategy with
`HELD_PAIR_ADD = {}` (on, defaults: one add, last fill >= 1 h old, any fresh signal), its .json
(the base's, renamed) when the base has one, and a plan copied from the control's plan -- same
folds, thresholds, model dirs and params snapshot (so the same 24 h grace pin); new run_id, class
names and arm tags. NNNC weights resolve to the control's per-fold model key (030), so nothing
trains; `run_folds` generates the per-fold classes `<arm class>_fNN`.

    PYTHONPATH=. ../../.venv/bin/python -m research.held_pair.build_arms [--only ARO] [--smoke]

`--smoke` also writes `plan_hp_smoke.json`: ARO's arm on f00 only, tag `hp_smoke` (031 T015).
"""

from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path


STRAT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
FOLDS = STRAT / "evaluation" / "folds"

#: book -> (arm tag, arm class, control tag, strategy group dir, window)
BOOKS = {
    "ARO": ("hp_aro_dca", "NNNC_HP_ARO_DCA", "wf_aro_g24", "NNNC", "2023-26"),
    "GBR": ("hp_gbr_dca", "NNNC_HP_GBR_DCA", "fs_gbr_gr", "NNNC", "2023-26"),
    "GFM": ("hp_gfm_dca", "NNNC_HP_GFM_DCA", "fs_gfm_gr", "NNNC", "2023-26"),
    "MLX": ("hp_mlx_dca", "NNNC_HP_MLX_DCA", "fs_mlx_gr", "NNNC", "2023-26"),
    "ST_REV": ("st_hp_rev", "SimpleTrigger_RevOnlyVolreg2_P2_G24_DCA", "st_g24_rev",
               "SimpleTrigger", "2023-26"),
    "ST_MOM": ("st_hp_mom", "SimpleTrigger_BreakoutGbb_MomExit_G24_DCA", "st_g24_mom",
               "SimpleTrigger", "2023-26"),
    "ST_REV_2022": ("st_e22_hp_rev", "SimpleTrigger_RevOnlyVolreg2_P2_G24_DCA",
                    "st_e22_g24_rev", "SimpleTrigger", "2022"),
    "ST_MOM_2022": ("st_e22_hp_mom", "SimpleTrigger_BreakoutGbb_MomExit_G24_DCA",
                    "st_e22_g24_mom", "SimpleTrigger", "2022"),
}

CLASS_TMPL = '''# pragma pylint: disable=C0103, C0114, C0115, C0116, C0301
# type: ignore
# pylint: disable=import-error
"""031 held-pair add (research/held_pair/): `{base}` (control `{control}`) with HELD_PAIR_ADD on.

A fresh entry signal on a pair that holds an open trade adds one stake to it (freqtrade position
adjustment); the trade's clocks then count from the last fill. Nothing else changes. GENERATED by
research/held_pair/build_arms.py.
"""

import sys
from pathlib import Path


sys.path.append(str(Path(__file__).parent))
sys.path.append(str(Path(__file__).parent.parent))

{imp}


class {name}({base}):
    HELD_PAIR_ADD = {{}}
'''


def build(book: str) -> dict:
    tag, name, ctl, group, window = BOOKS[book]
    plan = json.loads((FOLDS / f"plan_{ctl}.json").read_text())
    base = plan["base_strategy"]
    imp = (f"from {base} import {base}" if group == "NNNC"
           else f"from SimpleTrigger.{base} import {base}")
    py = STRAT / group / f"{name}.py"
    py.write_text(CLASS_TMPL.format(base=base, control=ctl, imp=imp, name=name))
    bj_path = STRAT / group / f"{base}.json"
    if bj_path.is_file():
        bj = json.loads(bj_path.read_text())
        bj["strategy_name"] = name
        (STRAT / group / f"{name}.json").write_text(json.dumps(bj, indent=4) + "\n")
    new = copy.deepcopy(plan)
    new["run_id"], new["base_strategy"] = tag, name
    for f in new["folds"]:
        cls = f.get("strategy_class")
        if cls == base:
            f["strategy_class"] = name
        elif cls:  # NNNC: per-fold classes are generated by run_folds from base_strategy
            f["strategy_class"] = f"{name}_{f['fold_id']}"
        f["arm_tag"] = f"{tag}_{f['fold_id']}"
        f["status"] = "planned"
    new["held_pair_note"] = f"031: {name} = {base} + HELD_PAIR_ADD {{}}; control {ctl}"
    (FOLDS / f"plan_{tag}.json").write_text(json.dumps(new, indent=1) + "\n")
    return {"book": book, "arm": tag, "class": name, "control": ctl, "window": window,
            "folds": [f["fold_id"] for f in new["folds"]]}


def smoke() -> None:
    plan = json.loads((FOLDS / "plan_hp_aro_dca.json").read_text())
    plan["run_id"] = "hp_smoke"
    plan["folds"] = [dict(f, arm_tag="hp_smoke_f00") for f in plan["folds"]
                     if f["fold_id"] == "f00"]
    (FOLDS / "plan_hp_smoke.json").write_text(json.dumps(plan, indent=1) + "\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--only", nargs="*", default=list(BOOKS))
    ap.add_argument("--smoke", action="store_true")
    a = ap.parse_args(argv)
    built = [build(b) for b in a.only]
    if a.smoke:
        smoke()
    arms_path = HERE / "arms.json"
    arms = json.loads(arms_path.read_text()) if arms_path.is_file() else {}
    arms.update({b["book"]: b for b in built})
    arms_path.write_text(json.dumps(arms, indent=1) + "\n")
    for b in built:
        print(f"{b['book']:12s} {b['arm']:15s} {b['class']:45s} control {b['control']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
