"""036 T006: train and pick the live NNNC model as one walk-forward fold (research R1).

    PYTHONPATH=. ../../.venv/bin/python -m research.live_pnl.live_fold --cut 20261016 --run-id live2 [--book aro]

`--book` chooses the live book (default `cs_aro`, the NNNC reference book since 2026-10-19):
- `cs_aro`: the width book with ARO's p_buy as a capital-neutral stake sizer (NNNC_CS_ARO; PASS
  PROVISIONAL, research/control_sizer/report.md). The bb_width cut is the latest evaluated fold's
  matched cut (research/model_calibration/width_twin.json, ARO; the causal rule of the width arms);
  the agree threshold is picked on the training window's validation tail at agree share 0.5
  (research.control_sizer.pick, then --verify). Held-pair add off, as in cs_aro.
- `aro`: the plain model book NNNC_A_Raw_Open (live1); threshold at target rate 0.014735 on the
  TRAINING window (the controls' rule; pick_threshold.py).
- `cs_aro_tr` (the NNNC reference since 2026-10-24): cs_aro + the 040 regime-transition exposure
  scaler, scored INSIDE the strategy (TR_SOURCE "standin"). Training and the sizer pick run on the
  cs_aro book (tr_scale does not change entries, so the threshold is cs_aro's); the transition
  stand-in is then fit at the cut (`research.nnmt.transition fit --cutoff <cut>`, its own process)
  and the fold class is regenerated on the tr book (`NNNC_LIVE_<run_id>_TRBOOK`, same model key). The
  bot needs the local 15m files (download-data) to reach its buffer start at every start: the
  long-window inputs come from utils/CloseHistoryStore (seeded from them, appended live).

The tool:
- builds `evaluation/folds/plan_live_<book>.json` from the control's plan (`plan_wf_aro_g24.json`):
  the same params snapshot, seed 1, one fold <run_id> with train `20210101-<cut>` and test
  `<cut>-<cut+90d>`; for cs_aro it first writes the book class `NNNC_LIVE_<run_id>_BOOK`
  (NNNC_CS_ARO with this fold's width cut), the plan's base;
- generates the fold class `NNNC_LIVE_<run_id>` and trains it if its model key has no weights
  (one trainer at a time; a cs_aro fold with an existing aro fold's cut reuses its weights);
- picks the threshold in its own process and regenerates the fold with it;
- writes the bot's class `NNNC_LIVE_<run_id>_REC` (ExecutionRecorderMixin + the fold class);
- appends a LiveModelRecord to research/live_pnl/live_models.json.

It refuses:
- while another training or backtest chain runs;
- a cut after the last downloaded 15m candle of any whitelist pair;
- an existing run_id.
"""

from __future__ import annotations

import argparse
import copy
import json
import os
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pandas as pd


STRAT = Path(__file__).resolve().parents[2]
ROOT = STRAT.parents[1]
for p in (STRAT, STRAT / "evaluation"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

HERE = Path(__file__).resolve().parent
FOLDS = STRAT / "evaluation" / "folds"
RECORDS = HERE / "live_models.json"
CONTROL_PLAN = "wf_aro_g24"
BOOKS = {"aro": "NNNC_A_Raw_Open", "cs_aro": "NNNC_CS_ARO", "cs_aro_tr": "NNNC_CS_ARO_TR"}
DEFAULT_BOOK = "cs_aro"
TARGET_RATE = 0.014735
WIDTH_TWIN = STRAT / "research" / "model_calibration" / "width_twin.json"
LIVE_DAYS = 90
DATA_DIR = STRAT.parent / "data" / "binanceus"
BUSY_EXTRA = ("research.live_pnl.live_fold ",)

REC_TEMPLATE = '''# pragma pylint: disable=C0103, C0114, C0115, C0116, C0301
# type: ignore
"""036 live bot strategy (GENERATED by research/live_pnl/live_fold.py): the live fold
`{fold_cls}` with the ExecutionRecorderMixin switched on. Same model key as the fold class."""

import sys
from pathlib import Path

sys.path.append(str(Path(__file__).parent))
sys.path.append(str(Path(__file__).parent.parent))

from utils.ExecutionRecorder import ExecutionRecorderMixin
from {fold_cls} import {fold_cls}


class {cls}(ExecutionRecorderMixin, {fold_cls}):
    RECORD_EXECUTION = True
    RECORD_DIR = str(Path(__file__).resolve().parents[2] / "data" / "live_nnnc")
    RECORD_RUN_ID = {run_id!r}
'''


BOOK_TEMPLATE = '''# pragma pylint: disable=C0103, C0114, C0115, C0116, C0301
# type: ignore
"""036 live book (GENERATED by research/live_pnl/live_fold.py): `NNNC_CS_ARO` with the live fold's
bb_width cut, {cut} = ARO's matched cut on {src} (width_twin.json; the width arms' causal rule)."""

import sys
from pathlib import Path

sys.path.append(str(Path(__file__).parent))

from NNNC_CS_ARO import NNNC_CS_ARO


class {cls}(NNNC_CS_ARO):
    WIDTH_CUTS = {{{train!r}: {cut!r}}}
'''


TRBOOK_TEMPLATE = '''# pragma pylint: disable=C0103, C0114, C0115, C0116, C0301
# type: ignore
"""Live book (GENERATED by research/live_pnl/live_fold.py): `NNNC_CS_ARO_TR` with the live fold's
bb_width cut ({cut}, as the cs_aro book) and the transition stand-in scored in-strategy at cutoff {stand_in}."""

import sys
from pathlib import Path

sys.path.append(str(Path(__file__).parent))

from NNNC_CS_ARO_TR import NNNC_CS_ARO_TR


class {cls}(NNNC_CS_ARO_TR):
    WIDTH_CUTS = {{{train!r}: {cut!r}}}
    TR_SOURCE = "standin"
    TR_STANDIN_CUTOFF = {stand_in!r}
'''


def trbook_class(run_id: str) -> str:
    return f"NNNC_LIVE_{run_id}_TRBOOK"


def fold_class(run_id: str) -> str:
    return f"NNNC_LIVE_{run_id}"


def book_class(run_id: str) -> str:
    return f"NNNC_LIVE_{run_id}_BOOK"


def plan_name(book: str) -> str:
    return f"plan_live_{book}.json"


def live_width_cut(twin: Path = WIDTH_TWIN) -> tuple[str, float]:
    """(fold id, cut): ARO's matched cut on the latest evaluated fold."""
    cuts = json.loads(twin.read_text())["models"]["ARO"]["cuts"]
    fid = max(cuts)
    return fid, float(cuts[fid])


def _book_source(run_id: str, train: str, cut: float, src: str) -> str:
    return BOOK_TEMPLATE.format(cls=book_class(run_id), train=train, cut=cut, src=src)


def build_plan(cut: str, run_id: str, control: dict, book: str = DEFAULT_BOOK) -> dict:
    """The one-fold live plan, from the control's plan (same params snapshot and sha)."""
    c = datetime.strptime(cut, "%Y%m%d").replace(tzinfo=timezone.utc)
    end = c + timedelta(days=LIVE_DAYS)
    cls = fold_class(run_id)
    tmpl = control["folds"][-1]
    fold = dict(tmpl, fold_id=run_id, train_start="2021-01-01",
                train_end=(c - timedelta(days=1)).strftime("%Y-%m-%d"),
                test_start=c.strftime("%Y-%m-%d"), test_end=end.strftime("%Y-%m-%d"),
                train_timerange=f"20210101-{cut}", test_timerange=f"{cut}-{end:%Y%m%d}",
                test_days=LIVE_DAYS, strategy_class=cls,
                model_dir=f"user_data/strategies/saved_data/{cls}", arm_tag=f"live_{book}_{run_id}",
                status="planned")
    plan = copy.deepcopy(control)
    rule = (f"threshold picked on the training window at target rate {TARGET_RATE}" if book == "aro" else
            "width-book entries (bb_width cut in the book class); sizer threshold picked on the training "
            "window's validation tail at agree share 0.5")
    plan.update(run_id=f"live_{book}", book=book, folds=[fold], data_end=cut,
                base_strategy=BOOKS[book] if book == "aro" else book_class(run_id),
                live_note=f"036 live model (research/live_pnl/live_fold.py): one fold trained to the cut; {rule}; "
                          "tested live as a dry-run.")
    for k in ("thresholds", "threshold_picks", "namespacing_note"):
        plan.pop(k, None)
    return plan


def last_candles(pairs: list[str], data_dir: Path = DATA_DIR) -> dict:
    out = {}
    for p in pairs:
        f = data_dir / f"{p.replace('/', '_')}-15m.feather"
        out[p] = pd.read_feather(f, columns=["date"])["date"].max() if f.is_file() else None
    return out


def refusals(cut: str, run_id: str, last: dict, records: list, busy: list[str]) -> list[str]:
    out = []
    if busy:
        out.append("another training/backtest chain is running: " + "; ".join(busy)[:300])
    if any(r["run_id"] == run_id for r in records):
        out.append(f"run_id {run_id} already exists in live_models.json")
    c = pd.Timestamp(datetime.strptime(cut, "%Y%m%d"), tz="UTC")
    need = c - pd.Timedelta(minutes=15)  # the training window's last candle
    short = [p for p, t in last.items() if t is None or t < need]
    if short:
        out.append(f"cut {cut} is after the last downloaded 15m candle of {short}")
    return out


def _busy() -> list[str]:
    from research.candidate_training import train as drv

    drv_busy = tuple(drv.BUSY) + BUSY_EXTRA
    old = drv.BUSY
    drv.BUSY = drv_busy
    try:
        return drv.other_chains(drv._ps(), os.getpid())
    finally:
        drv.BUSY = old


def _rec_source(run_id: str) -> str:
    fc = fold_class(run_id)
    return REC_TEMPLATE.format(fold_cls=fc, cls=f"{fc}_REC", run_id=run_id)


def _pick(plan_path: Path, run_id: str, book: str) -> float:
    """The live threshold, each pick in its own process (TF state); the fold class is regenerated
    with it (by --verify for cs_aro, which also checks every entry tag against the threshold)."""
    env = {**os.environ, "PYTHONPATH": f"{STRAT}{os.pathsep}{STRAT / 'evaluation'}"}
    if book == "aro":
        out = HERE / f"threshold_{run_id}.json"
        subprocess.run([sys.executable, str(STRAT / "evaluation" / "pick_threshold.py"),
                        "--plan", str(plan_path), "--fold", run_id,
                        "--target-rate", str(TARGET_RATE), "--out", str(out)],
                       cwd=ROOT, check=True, env={**os.environ, "PYTHONPATH": str(STRAT)})
        return float(json.loads(out.read_text())[run_id])
    for extra in ([], ["--verify"]):
        subprocess.run([sys.executable, "-m", "research.control_sizer.pick", "--plan", plan_path.name,
                        "--fold", run_id, *extra], cwd=STRAT, check=True, env=env)
    return float(json.loads(plan_path.read_text())["thresholds"][run_id])


def run(cut: str, run_id: str, book: str = DEFAULT_BOOK) -> dict:
    from evaluation.fingerprint import load_config
    import run_folds as RF

    control = json.loads((FOLDS / f"plan_{CONTROL_PLAN}.json").read_text())
    cfg = load_config(ROOT / control["config"])
    records = json.loads(RECORDS.read_text()) if RECORDS.is_file() else []
    bad = refusals(cut, run_id, last_candles(cfg["exchange"]["pair_whitelist"]), records, _busy())
    if bad:
        raise SystemExit("REFUSED:\n  " + "\n  ".join(bad))

    tr = book == "cs_aro_tr"
    if tr:
        book = "cs_aro"  # train and pick on the cs_aro book; the tr book replaces it at the end
    plan = build_plan(cut, run_id, control, book)
    fold = plan["folds"][0]
    width = None
    if book == "cs_aro":
        src, wcut = live_width_cut()
        width = {"cut": wcut, "from": f"width_twin.json ARO {src} matched cut"}
        plan["width_cut"] = width
        (STRAT / plan["family"] / f"{book_class(run_id)}.py").write_text(
            _book_source(run_id, fold["train_timerange"], wcut, src))
    base = plan["base_strategy"]
    plan_path = FOLDS / plan_name(book)
    plan_path.write_text(json.dumps(plan, indent=1) + "\n")
    params = json.loads((ROOT / plan["params_snapshot"]).read_bytes())

    RF.generate_fold(fold, base, plan["family"], params, seed=1)
    if not RF.fold_has_model(fold, base, plan["config"], 1):
        print(f"{run_id}: training {fold['strategy_class']} on {fold['train_timerange']}", flush=True)
        RF.train_fold(fold, plan["family"], 1, plan["config"])
        if not RF.fold_has_model(fold, base, plan["config"], 1):
            raise SystemExit(f"{run_id}: NO MODEL after training (see /tmp/wf_train_{fold['strategy_class']}.log)")

    threshold = _pick(plan_path, run_id, book)
    plan = json.loads(plan_path.read_text())  # cs_aro's picker stored threshold_picks there
    plan["thresholds"] = {run_id: threshold}
    plan_path.write_text(json.dumps(plan, indent=1) + "\n")
    stand_in = None
    if tr:
        env = {**os.environ, "PYTHONPATH": f"{STRAT}{os.pathsep}{STRAT / 'evaluation'}"}
        subprocess.run([sys.executable, "-m", "research.nnmt.transition", "fit", "--cutoff", cut],
                       cwd=STRAT, check=True, env=env)
        meta = STRAT / "saved_data" / "transition" / cut / "meta.json"
        if not meta.is_file():
            raise SystemExit(f"{run_id}: no transition stand-in at {meta}")
        stand_in = {"cutoff": cut, "meta": str(meta.relative_to(STRAT))}
        (STRAT / plan["family"] / f"{trbook_class(run_id)}.py").write_text(TRBOOK_TEMPLATE.format(
            cls=trbook_class(run_id), train=fold["train_timerange"], cut=width["cut"], stand_in=cut))
        base = trbook_class(run_id)
        plan["base_strategy"], plan["book"] = base, "cs_aro_tr"
        plan_path = FOLDS / plan_name("cs_aro_tr")
        plan_path.write_text(json.dumps(plan, indent=1) + "\n")
        book = "cs_aro_tr"
    RF.generate_fold(fold, base, plan["family"], params, threshold=threshold, seed=1)
    if tr and not RF.fold_has_model(fold, base, plan["config"], 1):
        raise SystemExit(f"{run_id}: the tr book moved the model key (no weights for {base})")

    fam = STRAT / plan["family"]
    rec_cls = f"{fold_class(run_id)}_REC"
    (fam / f"{rec_cls}.py").write_text(_rec_source(run_id))
    js = json.loads((fam / f"{fold_class(run_id)}.json").read_text())
    js["strategy_name"] = rec_cls
    (fam / f"{rec_cls}.json").write_text(json.dumps(js, indent=4) + "\n")

    from evaluation.fingerprint import load_strategy_class
    from Framework import ModelKey as MK

    key = MK.key_hash(MK.resolve(load_strategy_class(rec_cls), cfg))
    fold_key = MK.key_hash(MK.resolve(load_strategy_class(fold_class(run_id)), cfg))
    if key != fold_key:
        raise SystemExit(f"{rec_cls} key {key} != fold key {fold_key}")
    rec = {"run_id": run_id, "book": book, "strategy_class": fold_class(run_id), "bot_class": rec_cls,
           "model_key": key, "train_timerange": fold["train_timerange"], "threshold": threshold,
           "target_rate": TARGET_RATE if book == "aro" else None,
           "agree_share": None if book == "aro" else 0.5, "width_cut": width, "transition_stand_in": stand_in,
           "params_sha": plan.get("params_sha"),
           "status": "picked", "started": None, "retired": None}
    records.append(rec)
    RECORDS.write_text(json.dumps(records, indent=1) + "\n")
    print(json.dumps(rec, indent=1))
    return rec


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cut", required=True, help="YYYYMMDD: first day NOT in training")
    ap.add_argument("--run-id", required=True)
    ap.add_argument("--book", choices=sorted(BOOKS), default=DEFAULT_BOOK)
    a = ap.parse_args(argv)
    run(a.cut, a.run_id, a.book)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
