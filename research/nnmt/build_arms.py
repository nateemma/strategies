"""040 NNMT study: fold plans and arm classes (research R3-R12; contracts/cli.md).

Plans copy the 15 fold WINDOWS of the 039 plans verbatim (anchored 2021-01-01, 90-day tests f00-f14,
config_wf), so every NNMT arm is fold-for-fold comparable with NNNC / NNPredict / the width book. Each
arm gets its own fold-class prefix (`<TAG>_fNN`): foldplan's default `<family>_WF_fNN` would make
every NNMT plan generate the same classes.

  models     plans for mt, mt_fw0, mt_op and the four variants (research R4, R6)
  framework  the R7-selected model's feature arms + trading-head-only twin (research R5, R6)

    PYTHONPATH=.:evaluation ../../.venv/bin/python -m research.nnmt.build_arms models|framework
"""
from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

STRAT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(STRAT), str(STRAT / "evaluation"), str(STRAT / "NNMT"), str(STRAT / "NNNC"),
                str(STRAT / "NNPredict")]

HERE = Path(__file__).resolve().parent
FAMILY_DIR = STRAT / "NNMT"
FOLDS = STRAT / "evaluation" / "folds"
WINDOWS = FOLDS / "plan_nnp_lstm_ind_op.json"   # 039's 15 windows (= plan_cs_aro's)
CONFIG = {"exchange": {"pair_whitelist": ["SOL/USDT"]}, "timeframe": "15m"}

#: model stage: arm tag -> (class, note)
MODELS = {
    "mt": ("NNMT_MLX", "NNMT at its defaults, before the framework port (the identity reference)"),
    "mt_fw0": ("NNMT_MLX", "NNMT at its defaults on the framework base, everything off (identity)"),
    "mt_op": ("NNMT_MLX_OP", "NNMT at ARO's operating point (guards open, threshold 0.80)"),
    "mt_raw": ("NNMT_Raw", "current network on raw8, at the operating point"),
    "mt_lr": ("NNMT_LR", "plain multi-task LSTM (LSTM_RAW) on the 24 indicators, at the operating point"),
    "mt_lr_raw": ("NNMT_LR_Raw", "LSTM_RAW on raw8, at the operating point"),
    "mt_lr_ri": ("NNMT_LR_RI", "LSTM_RAW on the 24 indicators + raw8, at the operating point"),
    # architecture amendment (preregistration_arch.json); not an R7 candidate
    "mt_ls": ("NNMT_LS", "LSTM_STACK (shared LSTM + an LSTM per task) on the 24 indicators, at the operating point"),
}

HEADER = '''# pragma pylint: disable=C0103, C0114, C0115, C0116, C0301
# type: ignore
"""040 {stage} arm (GENERATED by research/nnmt/build_arms.py): {what}"""

import sys
from pathlib import Path

sys.path.append(str(Path(__file__).parent))
sys.path.append(str(Path(__file__).parent.parent / "NNNC"))
sys.path.append(str(Path(__file__).parent.parent / "NNPredict"))
'''


def plan(tag: str, cls: str, note: str, seed_tag: str | None = None) -> Path:
    """`evaluation/folds/plan_<tag>.json`: the 039 windows, family NNMT, fold classes `<TAG>_fNN`."""
    p = copy.deepcopy(json.loads(WINDOWS.read_text()))
    p.update(run_id=f"040_{tag}", family="NNMT", base_strategy=cls, params_snapshot=None,
             params_sha=None, note=f"040: {note}")
    for f in p["folds"]:
        fc = f"{tag.upper()}_{f['fold_id']}"
        f.update(strategy_class=fc, model_dir=f"user_data/strategies/saved_data/{fc}",
                 arm_tag=f"{tag}_{f['fold_id']}", status="planned")
        for k in ("n_trades", "model_artifact_verified", "arm_returncode"):
            f.pop(k, None)
    out = FOLDS / f"plan_{tag}.json"
    out.write_text(json.dumps(p, indent=1))
    return out


def write_class(name: str, base: str, stage: str, what: str, imports: str, body: str) -> Path:
    p = FAMILY_DIR / f"{name}.py"
    p.write_text(HEADER.format(stage=stage, what=what) + imports + f"\nfrom {base} import {base}\n\n\n"
                 f"class {name}({base}):\n" + body.format(base=base))
    return p


def key_of(cls_name: str) -> str:
    import importlib

    from Framework import ModelKey as MK

    mod = importlib.import_module(cls_name)
    return MK.key_hash(MK.resolve(getattr(mod, cls_name), CONFIG))


def models() -> dict:
    out = {tag: str(plan(tag, cls, note).relative_to(STRAT)) for tag, (cls, note) in MODELS.items()}
    print(json.dumps(out, indent=1))
    return out


#: framework stage: suffix -> (what, imports, body); every arm reuses the selected model's weights
#: except TR (trading head only: its own key, trained). Every arm is judged against the selected model
#: itself: all NNMT classes carry the framework since the port (T015), so its "fw0" IS the model.
FRAMEWORK = {
    "G24": ("24 h stoploss grace (NNNC's adopted value)",
            "from freqtrade.strategy import DecimalParameter\n",
            "    stoploss_grace_hours = DecimalParameter(0.0, 48.0, default=24.0, decimals=1, space=\"sell\",\n"
            "                                            load=True, optimize=False)\n"
            "    sell_params = {{**{base}.sell_params, \"stoploss_grace_hours\": 24.0}}\n"),
    "HPA": ("in-profit held-pair add (NNNC default since 2026-10-13)", "",
            "    HELD_PAIR_ADD = {{\"in_profit_only\": True}}\n"),
    "GATE": ("the model entry AND the gbb trigger (trigger_and_model)", "",
             "    ENTRY_MODE = \"trigger_and_model\"\n    TRIGGER_NAME = \"gbb\"\n"),
    "TP": ("C2 ATR take-profit (feature 028: 2.897 x ATR, clamped to [1%, 5%])", "",
           "    take_profit_atr_mult = 2.897\n"),
    "TR": ("trading head only (every auxiliary task weight 0): does multi-task training help?", "",
           "    _CLASSIFIER_TASK_WEIGHTS = {{**{base}._CLASSIFIER_TASK_WEIGHTS, \"regime\": 0.0, \"risk\": 0.0,\n"
           "                                \"momentum\": 0.0, \"flow\": 0.0, \"profit\": 0.0}}\n"),
}


def selected() -> tuple[str, str]:
    v = json.loads((HERE / "verdicts_models.json").read_text())
    sel = v.get("selected")
    if not sel:
        raise SystemExit("REFUSED: the models stage selected no model")
    return sel, MODELS[sel][0]


def framework() -> dict:
    tag, base = selected()
    out = {"selected": tag, "base": base, "arms": {}}
    for suffix, (what, imports, body) in FRAMEWORK.items():
        name = f"{base}_{suffix}"
        write_class(name, base, "framework", what, imports, body)
        arm = f"{tag}_{suffix.lower()}"
        plan(arm, name, f"framework stage (preregistration_framework.json): {what}")
        out["arms"][arm] = name
    k0 = key_of(base)
    bad = {a: c for a, c in out["arms"].items() if not a.endswith("_tr") and key_of(c) != k0}
    if bad:
        raise SystemExit(f"REFUSED: arms that would not reuse {base}'s weights: {bad}")
    if key_of(out["arms"][f"{tag}_tr"]) == k0:
        raise SystemExit("REFUSED: the trading-head-only twin resolves to the selected model's weights")
    print(json.dumps(out, indent=1))
    return out


def main(argv=None) -> int:
    stage = (argv or sys.argv[1:] or ["models"])[0]
    {"models": models, "framework": framework}[stage]()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
