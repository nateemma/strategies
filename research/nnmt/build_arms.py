def _derived_plan(src: str, tag: str, base: str, note: str, fold_class) -> Path:
    """plan_<tag>.json: `src`'s plan (windows, thresholds, params snapshot) with this arm's classes."""
    p = copy.deepcopy(json.loads((FOLDS / f"plan_{src}.json").read_text()))
    p.update(run_id=f"040_{tag}", base_strategy=base, note=f"040 T044: {note}")
    for f in p["folds"]:
        fc = fold_class(f["fold_id"])
        f.update(strategy_class=fc, arm_tag=f"{tag}_{f['fold_id']}", status="planned")
        if f.get("model_dir"):
            f["model_dir"] = f"user_data/strategies/saved_data/{fc}"
        for k in ("n_trades", "model_artifact_verified", "arm_returncode"):
            f.pop(k, None)
    out = FOLDS / f"plan_{tag}.json"
    out.write_text(json.dumps(p, indent=1))
    return out


def transition() -> dict:
    """The R12 arms for the selected transition cells: tr_gate / tr_scale / tr_exit on cs_aro (its weights,
    asserted by model key), tr_long standalone on st_g24_rev (one class per fold: a no-model plan runs
    its fold classes directly). An arm whose needed class selected no cell is not built."""
    sel = json.loads((HERE / "screens_transition.json").read_text())["selected"]
    cells = {"up": sel.get("up"), "down": sel.get("down")}
    out = {"cells": cells, "arms": {}, "not_built": {}}
    head = HEADER.format(stage="transition", what="{what}")
    for arm, (mixin, needs, what) in TRANSITION.items():
        if not any(cells[n] for n in needs) or (arm != "tr_scale" and not all(cells[n] for n in needs)):
            out["not_built"][arm] = f"no selected {'/'.join(needs)} cell"
            continue
        decl = f"    TR_UP_CELL = {cells['up']!r}\n    TR_DOWN_CELL = {cells['down']!r}\n"
        if arm == "tr_long":
            base, name = "SimpleTrigger_RevOnlyVolreg2_P2_G24", "SimpleTrigger_TR_LONG"
            body = (head.format(what=what) + "sys.path.append(str(Path(__file__).parent.parent))\n"
                    f"\nfrom _transition_signal import {mixin}\n"
                    f"from SimpleTrigger.{base} import {base}\n\n\nclass {name}({mixin}, {base}):\n{decl}")
            (ST_DIR / f"{name}.py").write_text(body)
            for f in json.loads((FOLDS / "plan_st_g24_rev.json").read_text())["folds"]:
                fc = f"TR_LONG_{f['fold_id']}"
                (ST_DIR / f"{fc}.py").write_text(
                    head.format(what=f"{what} -- fold {f['fold_id']}") + f"\nfrom {name} import {name}\n\n\n"
                    f"class {fc}({name}):\n    pass\n")
            out["arms"][arm] = str(_derived_plan("st_g24_rev", arm, name, what,
                                                 lambda fid: f"TR_LONG_{fid}").relative_to(STRAT))
            continue
        name = f"NNNC_{arm.upper()}"
        (STRAT / "NNNC" / f"{name}.py").write_text(
            head.format(what=what) + f"\nfrom _transition_signal import {mixin}\nfrom NNNC_CS_ARO import NNNC_CS_ARO\n"
            f"\n\nclass {name}({mixin}, NNNC_CS_ARO):\n{decl}")
        if key_of(name) != key_of("NNNC_CS_ARO"):
            raise SystemExit(f"REFUSED: {name} does not reuse NNNC_CS_ARO's weights")
        out["arms"][arm] = str(_derived_plan("cs_aro", arm, name, what,
                                             lambda fid, a=arm: f"{a.upper()}_{fid}").relative_to(STRAT))
    print(json.dumps(out, indent=1))
    return out


def transition_seed(arms: list[str], rs: int, kind: str = "rs") -> dict:
    """The pre-registered seed rerun of passing transition arms: the same arm on the stand-in re-fit at
    random_state `rs` (tables in nnmt_transition_<kind><rs>/, from `transition.py screen --random-state rs`
    [--bootstrap for kind "bs"]), as `<arm>_<kind><rs>` with fold classes `<ARM>_<KIND><rs>_fNN`."""
    out = {}
    head = HEADER.format(stage="transition seed rerun", what="{what}")
    decl = f'    TR_TABLES = TABLES.parent / "nnmt_transition_{kind}{rs}"\n'
    for arm in arms:
        what = f"{TRANSITION[arm][2]} -- stand-in re-fit at random_state {rs}" + (" on bootstrap rows" if kind == "bs" else "")
        tag, sfx = f"{arm}_{kind}{rs}", f"_{kind.upper()}{rs}"
        if arm == "tr_long":
            src, name = "SimpleTrigger_TR_LONG", f"SimpleTrigger_TR_LONG{sfx}"
            (ST_DIR / f"{name}.py").write_text(
                head.format(what=what) + "sys.path.append(str(Path(__file__).parent.parent))\n"
                f"\nfrom _transition_signal import TABLES\nfrom {src} import {src}\n\n\nclass {name}({src}):\n{decl}")
            for f in json.loads((FOLDS / "plan_st_g24_rev.json").read_text())["folds"]:
                fc = f"TR_LONG{sfx}_{f['fold_id']}"
                (ST_DIR / f"{fc}.py").write_text(
                    head.format(what=f"{what} -- fold {f['fold_id']}") + f"\nfrom {name} import {name}\n\n\n"
                    f"class {fc}({name}):\n    pass\n")
            out[tag] = str(_derived_plan("st_g24_rev", tag, name, what,
                                         lambda fid: f"TR_LONG{sfx}_{fid}").relative_to(STRAT))
            continue
        src, name = f"NNNC_{arm.upper()}", f"NNNC_{arm.upper()}{sfx}"
        (STRAT / "NNNC" / f"{name}.py").write_text(
            head.format(what=what) + f"\nfrom _transition_signal import TABLES\nfrom {src} import {src}\n"
            f"\n\nclass {name}({src}):\n{decl}")
        if key_of(name) != key_of("NNNC_CS_ARO"):
            raise SystemExit(f"REFUSED: {name} does not reuse NNNC_CS_ARO's weights")
        out[tag] = str(_derived_plan("cs_aro", tag, name, what,
                                     lambda fid, a=arm: f"{a.upper()}{sfx}_{fid}").relative_to(STRAT))
    print(json.dumps(out, indent=1))
    return out


#: T034 (preregistration_screens.json "sizer"): research.nnmt.pick writes {train_timerange: pick}
SIZER_THRESHOLDS = HERE / "sizer_thresholds.json"

SIZER_BODY = '''    """w_aro's width book sized by the NNMT model's p_buy (cs_aro pattern, contract C2)."""
    AGREE_RULE = "p_buy"
    WIDTH_CUTS = {cuts}
    #: MODEL_TRAIN_TIMERANGE -> the 0.5-agree-share threshold on p_buy (research.nnmt.pick)
    SIZER_THRESHOLDS = {thresholds}
    MODEL_KEY_IGNORED = ("SIZER_THRESHOLDS",)

    def get_entry_conditions(self, dataframe):
        # the fold's picked threshold, set here (after the model) and not in bot_start, a
        # weight-shaping method whose override would re-key the model (ModelMissing)
        key = getattr(self, "MODEL_TRAIN_TIMERANGE", None)
        if key in self.SIZER_THRESHOLDS:
            self.prediction_threshold = SimpleNamespace(value=float(self.SIZER_THRESHOLDS[key]))
        return super().get_entry_conditions(dataframe)
'''


def sizer() -> dict:
    """T034: <M>_wb = w_aro's width book and resolved framework on <M> (the identity twin: must equal
    w_aro on 15/15 before the sizer is read); <M>_cs = the same, sized by <M>'s p_buy at the per-fold
    thresholds in SIZER_THRESHOLDS (written only once that file covers all 15 folds)."""
    import importlib

    from evaluation import fingerprint as F
    from research.nnpredict.build_arms import WA_REFERENCE, _fingerprint_framework, width_cuts

    tag, base = selected()
    base_cls = getattr(importlib.import_module(base), base)
    sha, fw = _fingerprint_framework(base_cls, WA_REFERENCE[1])
    cuts = json.dumps(width_cuts(), indent=8, sort_keys=True)
    wb, cs = f"{base}_WB", f"{base}_CS"
    imports = "from freqtrade.strategy import DecimalParameter\n\nfrom _width_book import WidthBookMixin\n"
    p = write_class(wb, base, "sizer", "w_aro's width book and framework (identity twin of w_aro)", imports,
                    "    WIDTH_CUTS = " + cuts.replace("{", "{{").replace("}", "}}") + "\n" + fw)
    p.write_text(p.read_text().replace(f"class {wb}({base}):", f"class {wb}(WidthBookMixin, {base}):"))
    plan(f"{tag}_wb", wb, "sizer stage: w_aro's width book + framework on the selected model (identity twin)")
    out = {"selected": tag, "framework_sha": sha, "arms": {f"{tag}_wb": wb}}
    thr = json.loads(SIZER_THRESHOLDS.read_text()) if SIZER_THRESHOLDS.exists() else {}
    if len(thr) == 15:
        thresholds = {k: r["threshold"] for k, r in sorted(thr.items())}
        imports_cs = ("from types import SimpleNamespace\n\nfrom freqtrade.strategy import DecimalParameter\n\n"
                      "from _width_book import WidthBookMixin\nfrom _width_sizer import WidthSizerMixin\n")
        body = SIZER_BODY.replace("{thresholds}", json.dumps(thresholds, indent=8, sort_keys=True)).replace("{cuts}", cuts)
        p = write_class(cs, base, "sizer", "w_aro's width book sized by p_buy", imports_cs, "    pass\n")
        p.write_text(p.read_text().replace(f"class {cs}({base}):\n    pass\n",
                                           f"class {cs}(WidthSizerMixin, WidthBookMixin, {base}):\n" + body
                                           + fw.replace("{{", "{").replace("}}", "}")))
        plan(f"{tag}_cs", cs, "sizer stage: the p_buy sizer on w_aro's width book (preregistration_screens.json)")
        out["arms"][f"{tag}_cs"] = cs
    # every key w_aro resolves must match; keys w_aro does not have at all are NNMT's own model params
    # (apply_task_filters, bias_*, ...), listed, and the 15/15 trade identity of <M>_wb is the test
    cfg = str(STRAT / "config" / "config_wf.json")
    _, ref = F.resolve_by_name(WA_REFERENCE[1], cfg)
    for c in out["arms"].values():
        _, got = F.resolve_by_name(c, cfg)
        bad = {f"{s}.{k}": (v, (got.get(s) or {}).get(k)) for s, d in ref.items() if isinstance(d, dict)
               for k, v in d.items() if (got.get(s) or {}).get(k) != v}
        bad.update({s: "differs" for s, d in ref.items() if not isinstance(d, dict) and got.get(s) != d})
        if bad:
            raise SystemExit(f"REFUSED: {c} differs from {WA_REFERENCE[0]}'s framework: {bad}")
        out.setdefault("model_only_keys", {})[c] = sorted(
            f"{s}.{k}" for s, d in got.items() if isinstance(d, dict) for k in d if k not in (ref.get(s) or {}))
    k0 = key_of(base)
    bad = {c: key_of(c) for c in out["arms"].values() if key_of(c) != k0}
    if bad:
        raise SystemExit(f"REFUSED: arms that would not reuse {base}'s weights: {bad}")
    print(json.dumps(out, indent=1))
    return out


def main(argv=None) -> int:
    args = argv or sys.argv[1:] or ["models"]
    stage = args[0]
    if stage == "transition-seed":
        transition_seed(args[1].split(","), int(args[2]), *(args[3:4] or []))
        return 0
    {"models": models, "framework": framework, "heads": heads, "regime": regime,
     "transition": transition, "trh": trh, "sizer": sizer}[stage]()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
