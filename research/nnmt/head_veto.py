"""040 follow-up arms (preregistration_own_trade_heads.json, amendment 2026-10-26): hd_profit_g24 (veto on the heads-trained
model's P(profit), run in-process) and its model-free twin hd_atr_g24 (veto on atr_pct_roll), both on mt_lr_ri_g24.

  build              NNMT_LR_RI_G24_HDP / _ATRV (VETO_THRESHOLDS from veto_thresholds.json, None until picked),
                     plan_hd_profit_g24 / plan_hd_atr_g24 (+ _s2), model keys asserted == NNMT_LR_RI's
  pick  ARM FOLD     the 20th percentile of the veto score over the fold's validation-tail entry bars (veto off),
                     one process per fold                                   -> veto_thresholds.json
  check ARM FOLD     on the fold's test window, veto on: entries == the model's entries (MT_LR_RI_G24 table) AND
                     score >= threshold; hd_profit_g24 also: score == MT_LR_RI_AH's table p_profit_profit
                                                                          -> veto_check.json
  judge              the amended rule                                        -> verdicts_own_trade_heads.json

    PYTHONPATH=.:evaluation ../../.venv/bin/python -m research.nnmt.head_veto build

Seed 2: run_folds --plan plan_<arm>_s2.json --seed 2 appends a second _s2 (records <arm>_fNN_s2_s2_FNN.json); rename
them to the plan's arm_tag (<arm>_fNN_s2_FNN.json) and judge through research.nnmt.judge._by_plan_arm_tag.
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

STRAT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(STRAT), str(STRAT / "evaluation"), str(STRAT / "NNMT"), str(STRAT / "NNNC")]
HERE = Path(__file__).resolve().parent
FOLDS = STRAT / "evaluation" / "folds"
SIG = STRAT / "research" / "nnnc_framework" / "signals"
THR = HERE / "veto_thresholds.json"
CHK = HERE / "veto_check.json"
PREREG = HERE / "preregistration_own_trade_heads.json"
BASE = "NNMT_LR_RI_G24_PreTR"

ARMS = {
    "hd_profit_g24": {"cls": "NNMT_LR_RI_G24_HDP", "column": "p_profit_profit", "model": "MT_LR_RI_AH",
                      "mainline": "NNMT_LR_RI_AH", "dp": 4,
                      "doc": "no entry when the heads-trained model's (MT_LR_RI_AH, run in-process) P(profit) < the fold's threshold"},
    "hd_atr_g24": {"cls": "NNMT_LR_RI_G24_ATRV", "column": "atr_pct_roll", "model": None, "mainline": None, "dp": 6,
                   "doc": "model-free twin: no entry when atr_pct_roll < the fold's threshold"},
}

TMPL = '''# pragma pylint: disable=C0103, C0114, C0115, C0116, C0301
# type: ignore
"""040 follow-up arm (GENERATED by research/nnmt/head_veto.py; preregistration_own_trade_heads.json): mt_lr_ri_g24
({base}, tr_scale off as its records) + {doc}. Post-model: NNMT_LR_RI's weights."""

import sys
from pathlib import Path

sys.path.append(str(Path(__file__).parent))

from _head_veto import HeadVetoMixin
from {base} import {base}


class {name}(HeadVetoMixin, {base}):
    VETO_COLUMN = {column!r}
    VETO_MODEL = {model!r}
    VETO_MAINLINE = {mainline!r}
    VETO_THRESHOLDS = {thresholds}
'''


def _plan(tag: str) -> dict:
    return json.loads((FOLDS / f"plan_{tag}.json").read_text())


def _thresholds() -> dict:
    return json.loads(THR.read_text()) if THR.is_file() else {}


def build() -> int:
    from research.nnmt.build_arms import key_of

    thr = _thresholds()
    for arm, a in ARMS.items():
        t = thr.get(arm) or {}
        lit = "None" if len(t) < 15 else "{\n" + "".join(f"        {k!r}: {v!r},\n" for k, v in sorted(t.items())) + "    }"
        (STRAT / "NNMT" / f"{a['cls']}.py").write_text(TMPL.format(
            base=BASE, name=a["cls"], doc=a["doc"], column=a["column"], model=a["model"], mainline=a["mainline"], thresholds=lit))
        for src, suf in (("mt_lr_ri_g24", ""), ("mt_lr_ri_g24_s2", "_s2")):
            p = copy.deepcopy(_plan(src))
            p.update(run_id=f"040_{arm}{suf}", base_strategy=a["cls"], note=f"040 follow-up: {a['doc']} (preregistration_own_trade_heads.json)")
            for f in p["folds"]:
                fc = f"{arm.upper()}_{f['fold_id']}{suf}"
                f.update(strategy_class=fc, model_dir=f"user_data/strategies/saved_data/{fc}",
                         arm_tag=f"{arm}_{f['fold_id']}{suf}", status="planned")
                for k in ("n_trades", "model_artifact_verified", "arm_returncode"):
                    f.pop(k, None)
            (FOLDS / f"plan_{arm}{suf}.json").write_text(json.dumps(p, indent=1))
    keys = {n: key_of(n) for n in ("NNMT_LR_RI", BASE, *(a["cls"] for a in ARMS.values()))}
    if len(set(keys.values())) != 1:
        raise SystemExit(f"REFUSED: model keys differ: {keys}")
    print(json.dumps({"built": [a["cls"] for a in ARMS.values()], "key": keys["NNMT_LR_RI"],
                      "thresholds": {arm: len(thr.get(arm) or {}) for arm in ARMS}}))
    return 0


def _fold(arm: str, fid: str, seed: int) -> tuple[dict, dict]:
    import run_folds as rf

    plan = _plan(arm if seed == 1 else f"{arm}_s{seed}")
    f = next(x for x in plan["folds"] if x["fold_id"] == fid)
    rf.generate_fold(f, plan["base_strategy"], plan["family"], None, seed=seed)
    return plan, f


def _key(f: dict, seed: int) -> str:
    return f["train_timerange"] if seed == 1 else f"{f['train_timerange']}_s{seed}"


def pick(arm: str, fid: str, seed: int) -> int:
    from research.width_relative import pick as WP

    os.environ["FT_VETO_OFF"] = "1"
    plan, f = _fold(arm, fid, seed)
    frames, _ = WP._frames(plan, fid, None)
    sc = np.concatenate([s["veto_score"].to_numpy(float)[s["enter_long"].fillna(0).to_numpy() == 1] for s in frames.values()])
    fin = sc[np.isfinite(sc)]
    t = round(float(np.quantile(fin, 0.2)), ARMS[arm]["dp"])
    thr = _thresholds()
    thr.setdefault(arm, {})[_key(f, seed)] = t
    thr.setdefault("_picks", {})[f"{arm}:{fid}:s{seed}"] = {"entry_bars": int(len(sc)), "finite": int(len(fin)),
                                                           "vetoed_share": round(float(np.mean(~(sc >= t))), 4)}
    THR.write_text(json.dumps(thr, indent=1))
    print(json.dumps({"arm": arm, "fold": fid, "seed": seed, "threshold": t, **thr["_picks"][f"{arm}:{fid}:s{seed}"]}))
    return 0


def check(arm: str, fid: str, seed: int) -> int:
    """Test window, veto on. Seed 1 only (the reference tables are seed-1)."""
    from freqtrade.configuration import TimeRange
    from freqtrade.data import history
    from freqtrade.data.converter import trim_dataframe
    from pick_threshold import _load_fold_context

    plan, f = _fold(arm, fid, seed)
    strat, cfg = _load_fold_context(f["strategy_class"], plan["family"], plan["config"])
    strat.ft_load_hyper_params(False)
    strat.ensure_veto_weights()
    t = strat.veto_threshold()
    tr = TimeRange.parse_timerange(f["test_timerange"])
    data = history.load_data(datadir=cfg["datadir"], pairs=cfg["exchange"]["pair_whitelist"], timeframe=cfg["timeframe"],
                             timerange=tr, startup_candles=strat.startup_candle_count, fail_without_data=True,
                             data_format=cfg.get("dataformat_ohlcv", "feather"), candle_type=cfg.get("candle_type_def", "spot"))
    ref = pd.read_parquet(SIG / f"MT_LR_RI_{fid}.parquet")
    ah = pd.read_parquet(SIG / f"MT_LR_RI_AH_{fid}.parquet") if ARMS[arm]["model"] else None
    rows = []
    for pair, df in strat.advise_all_indicators(data).items():
        s = trim_dataframe(strat.advise_entry(df.copy(), {"pair": pair}), tr, startup_candles=strat.startup_candle_count)
        d = pd.DataFrame({"pair": pair, "date": pd.to_datetime(s["date"], utc=True), "enter": s["enter_long"].fillna(0).to_numpy() == 1,
                          "score": s["veto_score"].to_numpy(float)})
        rows.append(d)
    d = pd.concat(rows, ignore_index=True)
    r = ref.assign(date=pd.to_datetime(ref["date"], utc=True))[["pair", "date", "enter_long"]]
    m = d.merge(r, on=["pair", "date"], how="left")
    want = (m["enter_long"] == 1) & (m["score"] >= t)
    out = {"threshold": t, "bars": len(m), "model_entries": int((m["enter_long"] == 1).sum()), "arm_entries": int(m["enter"].sum()),
           "entry_mismatch": int((m["enter"] != want).sum()), "vetoed": int(((m["enter_long"] == 1) & ~want).sum())}
    if ah is not None:
        a = ah.assign(date=pd.to_datetime(ah["date"], utc=True))[["pair", "date", ARMS[arm]["column"]]]
        mm = m.merge(a, on=["pair", "date"], how="left")
        e = mm["enter_long"] == 1
        diff = (mm["score"] - mm[ARMS[arm]["column"]]).abs()
        out["score_vs_table_entry_bars"] = {"n": int(e.sum()), "max_abs_diff": float(diff[e].max()),
                                            "share_within_1e-5": round(float((diff[e] <= 1e-5).mean()), 5)}
    out["pass"] = bool(out["entry_mismatch"] == 0 and (ah is None or out["score_vs_table_entry_bars"]["share_within_1e-5"] >= 0.999))
    res = json.loads(CHK.read_text()) if CHK.is_file() else {}
    res[f"{arm}:{fid}"] = out
    CHK.write_text(json.dumps(res, indent=1))
    print(json.dumps({"arm": arm, "fold": fid, **out}))
    return 0 if out["pass"] else 1


def judge() -> int:
    from research.nnnc_switches.judge import judge_one
    from research.pair_triggers import judge as PJ

    pr = json.loads(PREREG.read_text())
    PJ.PREREG = PREREG
    bad = PJ.refusals(pr)
    if bad:
        raise SystemExit(f"REFUSED: {bad}")
    chk = json.loads(CHK.read_text()) if CHK.is_file() else {}
    missing = [f"{a}:{f}" for a in ARMS for f in pr["folds"] if not (chk.get(f"{a}:{f}") or {}).get("pass")]
    rule = {**pr, "rule": json.loads((HERE / "preregistration_screens.json").read_text())["rule"], "min_control_trades": 200}
    out = {"label": pr["label"], "instrument": {"check_failed_or_missing": missing}}
    if missing:
        out["verdicts"] = "INCONCLUSIVE (instrument)"
    else:
        v = {"hd_atr_g24 vs mt_lr_ri_g24": judge_one(rule, "hd_atr_g24", "mt_lr_ri_g24"),
             "hd_profit_g24 vs mt_lr_ri_g24": judge_one(rule, "hd_profit_g24", "mt_lr_ri_g24"),
             "hd_profit_g24 vs hd_atr_g24": judge_one(rule, "hd_profit_g24", "hd_atr_g24")}
        p1, p2 = v["hd_profit_g24 vs mt_lr_ri_g24"]["verdict"], v["hd_profit_g24 vs hd_atr_g24"]["verdict"]
        out["verdicts"] = v
        out["decision"] = {
            "hd_atr_g24": "PASS (PROVISIONAL; seed 2 next)" if v["hd_atr_g24 vs mt_lr_ri_g24"]["verdict"] == "PASS" else v["hd_atr_g24 vs mt_lr_ri_g24"]["verdict"],
            "hd_profit_g24": ("PASS (PROVISIONAL; seed 2 next)" if p1 == "PASS" and p2 == "PASS" else
                              "gain is volatility (beats mt_lr_ri_g24, not the twin)" if p1 == "PASS" else p1)}
        out["beside"] = {a: {ref: judge_one(rule, a, ref) for ref in ("cs_aro_tr", "w_free")} for a in ARMS}
    (HERE / "verdicts_own_trade_heads.json").write_text(json.dumps(out, indent=1, default=str))
    print(json.dumps({k: out[k] for k in ("instrument", "decision") if k in out} or out, indent=1, default=str))
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=("build", "pick", "check", "judge"))
    ap.add_argument("arm", nargs="?", choices=tuple(ARMS))
    ap.add_argument("fold", nargs="?")
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args(argv)
    if a.step in ("build", "judge"):
        return build() if a.step == "build" else judge()
    if not (a.arm and a.fold):
        ap.error("pick / check need ARM FOLD")
    return (pick if a.step == "pick" else check)(a.arm, a.fold, a.seed)


if __name__ == "__main__":
    raise SystemExit(main())
