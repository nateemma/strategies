"""035 T022: generate the survivor classes and plans (research R9; contract new_input_mixin).

Per survivor tag T (arms.survivors(): S1b's list, else S1's):

  * `NNNC/NNNC_NI_<T>.py`    = NewInputMixin + NNNC_A_Raw_Open, NEW_INPUTS = (T,), include_list and
                               pre_normalized_columns = the control's + T's columns (new lists),
                               NEW_INPUTS_SHA = the input table's sha. The training class.
  * `NNNC/NNNC_NI_<T>_SZ.py` = NewInputMixin + NNNC_CS_ARO with the same declarations: the control
                               sizer with only the weights changed (same model key as the above).

Plans: `plan_ni_<t>.json` copied from the control's `plan_wf_aro_g24.json` (training, tables) and
`plan_ni_<t>_sz.json` copied from `plan_cs_aro.json` (the S3 arm); new classes and arm tags, no
thresholds. `.json` params copied from the control's.

    PYTHONPATH=. ../../.venv/bin/python -m research.new_inputs.build_arms
"""

from __future__ import annotations

import copy
import json
import sys
from pathlib import Path


STRAT = Path(__file__).resolve().parents[2]
if str(STRAT) not in sys.path:
    sys.path.insert(0, str(STRAT))

from research.new_inputs import arms as A  # noqa: E402
from research.new_inputs import inputs as I  # noqa: E402


FOLDS = STRAT / "evaluation" / "folds"
NNNC = STRAT / "NNNC"
#: per model: (control plan, sizer plan, training base class, sizer base class)
BASES = {"ARO": ("wf_aro_g24", "cs_aro", "NNNC_A_Raw_Open", "NNNC_CS_ARO"),
         "GBR": ("fs_gbr_gr", "cs_gbr", "NNNC_GbbRaw_Open", "NNNC_CS_GBR")}
CONTROL_PLAN, SIZER_PLAN, CONTROL_CLASS, SIZER_CLASS = BASES["ARO"]

TMPL = '''# pragma pylint: disable=C0103, C0114, C0115, C0116, C0301
# type: ignore
"""{doc}"""

import sys
from pathlib import Path


sys.path.append(str(Path(__file__).parent))
sys.path.append(str(Path(__file__).parent.parent))

from _new_inputs import NewInputMixin
from {base} import {base}


class {name}(NewInputMixin, {base}):
    NEW_INPUTS = {inputs!r}
    NEW_INPUTS_SHA = {sha!r}
    NEW_INPUT_COLUMNS = {cols!r}
    include_list = list({base}.include_list) + list(NEW_INPUT_COLUMNS)
    pre_normalized_columns = list({base}.pre_normalized_columns) + list(NEW_INPUT_COLUMNS)
'''


NULL = "NULL"   # the no-input retrain: the survivor pipeline with nothing added (preregistration_null)


def _write_class(name: str, base: str, tag: str, doc: str, base_json: str) -> None:
    cols = () if tag == NULL else tuple(I.columns(tag))
    inputs = () if tag == NULL else (tag,)
    (NNNC / f"{name}.py").write_text(TMPL.format(doc=doc, base=base, name=name, inputs=inputs,
                                                 sha=I.TABLE_SHA, cols=cols))
    bj = json.loads((NNNC / f"{base_json}.json").read_text())
    bj["strategy_name"] = name
    (NNNC / f"{name}.json").write_text(json.dumps(bj, indent=4) + "\n")


def _plan(src: str, run_id: str, cls: str) -> dict:
    p = copy.deepcopy(json.loads((FOLDS / f"plan_{src}.json").read_text()))
    p["run_id"], p["base_strategy"] = run_id, cls
    for k in ("thresholds", "threshold_picks", "cs_note", "ls_note"):
        p.pop(k, None)
    p["ni_note"] = (f"035 new-input screen: {cls}; copied from plan_{src}.json "
                    "(research/new_inputs/build_arms.py)")
    for f in p["folds"]:
        f["strategy_class"] = f"{cls}_{f['fold_id']}"
        f["model_dir"] = f"user_data/strategies/saved_data/{cls}_{f['fold_id']}"
        f["arm_tag"] = f"{run_id}_{f['fold_id']}"
        f["status"] = "planned"
    return p


def build(tags=None, model: str = "ARO") -> dict:
    ctl_plan, sz_plan, ctl_cls, sz_cls = BASES[model]
    out = {}
    for tag in tags or A.survivors(model):
        name = A.class_name(tag, model)
        doc = (f"035 new-input screen (GENERATED by research/new_inputs/build_arms.py): "
               f"`{ctl_cls}` plus the input {tag} as a pre-normalised column; everything "
               f"else is the control's (control scaler unchanged).")
        _write_class(name, ctl_cls, tag, doc, ctl_cls)
        _write_class(f"{name}_SZ", sz_cls, tag, doc + " Width-book sizer (the control "
                     "sizer with only the weights changed).", sz_cls)
        for src, role, cls in ((ctl_plan, "entry", name), (sz_plan, "sz", f"{name}_SZ")):
            rid = A.plan_tag(tag, role, model)
            (FOLDS / f"plan_{rid}.json").write_text(json.dumps(_plan(src, rid, cls), indent=1)
                                                    + "\n")
            out[rid] = cls
    return out


def main() -> int:
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--model", choices=sorted(BASES), default="ARO")
    for k, v in build(model=ap.parse_args().model).items():
        print(k, v)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
