"""039: write the framework-stage and sizer-stage arm classes and fold plans for the model the
operating-point stage selected (research R6-R8; verdicts_op.json "selected").

  framework  <C>_FW0 (nothing declared: the identity arm), _G24 (24 h stoploss grace), _HPA (in-profit
             held-pair add), _FAMM (momentum family exits), _GATE (model AND the gbb trigger).
             Every arm reuses <C>'s weights: their model keys are asserted equal.
  sizer      <C>_WB (the width book on <C>'s exits: the sizer's own control) and <C>_CS (the width book
             sized by NNPredict's predicted move, AGREE_RULE p_buy, sizer_score = %predict_gain, a
             per-fold 0.5-agree-share threshold picked by research.nnpredict.pick).

    PYTHONPATH=.:evaluation ../../.venv/bin/python -m research.nnpredict.build_arms framework|sizer|followups
"""
from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

STRAT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(STRAT), str(STRAT / "evaluation"), str(STRAT / "NNPredict"), str(STRAT / "NNNC")]

HERE = Path(__file__).resolve().parent
FAMILY_DIR = STRAT / "NNPredict"
FOLDS = STRAT / "evaluation" / "folds"
CONFIG = {"exchange": {"pair_whitelist": ["SOL/USDT"]}, "timeframe": "15m"}

HEADER = '''# pragma pylint: disable=C0103, C0114, C0115, C0116, C0301
# type: ignore
"""039 {stage} arm (GENERATED by research/nnpredict/build_arms.py): {what}"""

import sys
from pathlib import Path

sys.path.append(str(Path(__file__).parent))
sys.path.append(str(Path(__file__).parent.parent / "NNNC"))
'''

FRAMEWORK = {
    "FW0": ("identity: nothing declared (the ported framework, everything off)", "", "    pass\n"),
    "G24": ("24 h stoploss grace (NNNC's adopted value; the base parameter range only reaches 6 h)",
            "from freqtrade.strategy import DecimalParameter\n",
            "    stoploss_grace_hours = DecimalParameter(0.0, 48.0, default=24.0, decimals=1, space=\"sell\",\n"
            "                                            load=True, optimize=False)\n"
            "    sell_params = {{**{base}.sell_params, \"stoploss_grace_hours\": 24.0}}\n"),
    "HPA": ("in-profit held-pair add (NNNC default since 2026-10-13)", "",
            "    HELD_PAIR_ADD = {{\"in_profit_only\": True}}\n"),
    "FAMM": ("momentum family exits (ARM_D_FAMILY momentum set: no take-profit, 24 h unclog)", "",
             "    MODEL_ENTRY_FAMILY = \"momentum\"\n"
             "    FAMILY_EXIT_OVERRIDES = {{\"momentum\": {{\"take_profit\": 10.0, \"unclog_12h_hours\": 24.0}}}}\n"),
    "GATE": ("the model entry AND the gbb trigger (trigger_and_model)", "",
             "    ENTRY_MODE = \"trigger_and_model\"\n    TRIGGER_NAME = \"gbb\"\n"),
}


def selected() -> tuple[str, str]:
    """(arm tag, class) of the R7 selection: over the operating-point and threshold-amendment arms once
    verdicts_threshold.json exists, else the operating-point stage's."""
    th = HERE / "verdicts_threshold.json"
    sel = (json.loads(th.read_text())["selected_union"] if th.exists()
           else json.loads((HERE / "verdicts_op.json").read_text())["selected"])
    if not sel:
        raise SystemExit("REFUSED: no model was selected by the operating-point stage")
    arms = {**json.loads((HERE / "preregistration_op.json").read_text())["arms"],
            **json.loads((HERE / "preregistration_threshold.json").read_text())["arms"]}
    return sel, arms[sel]["class"]


def _write_class(name: str, base: str, stage: str, what: str, imports: str, body: str) -> Path:
    p = FAMILY_DIR / f"{name}.py"
    p.write_text(HEADER.format(stage=stage, what=what) + imports + f"\nfrom {base} import {base}\n\n\n"
                 f"class {name}({base}):\n" + body.format(base=base))
    return p


def _plan(src_tag: str, tag: str, cls: str, note: str) -> Path:
    p = copy.deepcopy(json.loads((FOLDS / f"plan_{src_tag}.json").read_text()))
    p.update(run_id=f"039_{tag}", base_strategy=cls, note=note)
    for f in p["folds"]:
        fc = f"{tag.upper()}_{f['fold_id']}"
        f.update(strategy_class=fc, model_dir=f"user_data/strategies/saved_data/{fc}",
                 arm_tag=f"{tag}_{f['fold_id']}", status="planned")
        for k in ("n_trades", "model_artifact_verified", "arm_returncode"):
            f.pop(k, None)
    out = FOLDS / f"plan_{tag}.json"
    out.write_text(json.dumps(p, indent=1))
    return out


def _key(cls_name: str) -> str:
    import importlib

    from Framework import ModelKey as MK

    mod = importlib.import_module(cls_name)
    return MK.key_hash(MK.resolve(getattr(mod, cls_name), CONFIG))


def framework() -> dict:
    tag, base = selected()
    out = {"selected": tag, "base": base, "arms": {}}
    for suffix, (what, imports, body) in FRAMEWORK.items():
        name = f"{base}_{suffix}"
        _write_class(name, base, "framework", what, imports, body)
        arm = f"{tag}_{suffix.lower()}"
        _plan(tag, arm, name, f"039 framework stage (preregistration_framework.json): {what}")
        out["arms"][arm] = name
    k0 = _key(base)
    bad = {a: c for a, c in out["arms"].items() if _key(c) != k0}
    if bad:
        raise SystemExit(f"REFUSED: arms that would not reuse {base}'s weights: {bad}")
    print(json.dumps(out, indent=1))
    return out


SIZER_BODY = '''    """The width book sized by NNPredict's predicted move (cs_aro pattern, contract C2)."""
    AGREE_RULE = "p_buy"
    WIDTH_CUTS = {cuts}
    #: MODEL_TRAIN_TIMERANGE -> the 0.5-agree-share threshold on %predict_gain (research.nnpredict.pick)
    SIZER_THRESHOLDS = {thresholds}
    MODEL_KEY_IGNORED = ("SIZER_THRESHOLDS",)

    def sizer_score(self, dataframe):
        return dataframe["%predict_gain"].to_numpy(float)

    def bot_start(self, **kwargs) -> None:
        super().bot_start(**kwargs)
        key = getattr(self, "MODEL_TRAIN_TIMERANGE", None)
        if key in self.SIZER_THRESHOLDS:  # a fold class: its own picked threshold
            self.prediction_threshold = SimpleNamespace(value=float(self.SIZER_THRESHOLDS[key]))
'''


def width_cuts() -> dict:
    """cs_aro's / w_aro's exact per-fold cuts (NNNC_LS_CONTROL_SZ.WIDTH_CUTS), read here and written as a
    literal, so the NNPredict classes never import the NNNC chain."""
    import re

    src = (STRAT / "NNNC" / "NNNC_LS_CONTROL_SZ.py").read_text()
    body = re.search(r"WIDTH_CUTS = \{(.*?)\}", src, re.S).group(1)
    return {k: float(v) for k, v in re.findall(r"'(\d{8}-\d{8})': ([0-9.eE-]+)", body)}


def sizer(thresholds: dict | None = None) -> dict:
    tag, base = selected()
    cuts = json.dumps(width_cuts(), indent=8, sort_keys=True)
    fw0 = f"{base}_FW0"
    wb, cs = f"{base}_WB", f"{base}_CS"
    imports = "from _width_book import WidthBookMixin\n"
    _write_class(wb, fw0, "sizer", "the width book on the NNPredict model's own exits (the sizer's control)",
                 imports, f"    WIDTH_CUTS = {cuts}\n").write_text(
        (FAMILY_DIR / f"{wb}.py").read_text().replace(f"class {wb}({fw0}):", f"class {wb}(WidthBookMixin, {fw0}):"))
    _plan(tag, f"{tag}_wb", wb, "039 sizer stage: the width book on the selected model's exits")
    if thresholds is not None:
        imports_cs = ("from types import SimpleNamespace\n\n"
                      "from _width_book import WidthBookMixin\nfrom _width_sizer import WidthSizerMixin\n")
        body = SIZER_BODY.replace("{thresholds}", json.dumps(thresholds, indent=8, sort_keys=True)).replace("{cuts}", cuts)
        p = _write_class(cs, fw0, "sizer", "the width book sized by the predicted move", imports_cs, "    pass\n")
        p.write_text(p.read_text().replace(f"class {cs}({fw0}):\n    pass\n",
                                           f"class {cs}(WidthSizerMixin, WidthBookMixin, {fw0}):\n" + body))
        _plan(tag, f"{tag}_cs", cs, "039 sizer stage: the predicted-move sizer (preregistration_sizer.json)")
    out = {"selected": tag, "width_book": wb, "sizer": cs if thresholds is not None else None}
    print(json.dumps(out, indent=1))
    return out


#: The reference whose framework the REV arms copy: st_g24_rev (gbb reversion, volreg2 gate, C2 ATR
#: take-profit, 24 h grace) -- research/nnpredict/preregistration_followups.json.
REV_REFERENCE = ("st_g24_rev", "SimpleTrigger.SimpleTrigger_RevOnlyVolreg2_P2_G24")


def _st_framework(base_cls, st_cls) -> str:
    """Class body that puts `st_cls`'s resolved framework (preset attributes, guard and exit params,
    family exits, regime gate, triggers) on an NNPredict class, as literals (attributes only where
    they differ from the base's). The model's own entry
    params (buy_params beyond the guards) are kept, so only the entry source can differ."""
    from SimpleTrigger import presets as P

    preset = P.get(st_cls.PRESET)
    lines = []
    for k in sorted(preset["attributes"]):
        if not hasattr(st_cls, k):  # the preset leaves it unset (freqtrade's default)
            continue
        v = getattr(st_cls, k)
        if hasattr(base_cls, k) and getattr(base_cls, k) == v:  # already the base's value
            continue
        lines.append(f"    {k} = {v!r}")
    guards = {k: st_cls.buy_params[k] for k in preset["buy"]}
    pin = {"startup_candle_count": int(getattr(base_cls, "startup_candle_count"))}
    lines += [
        f"    MODEL_TRAINED_WITH = {pin!r}  # the weights were trained with the base warm-up",
        f"    TRIGGERS = {tuple(st_cls.TRIGGERS)!r}",
        f"    DISABLED_TRIGGERS = {tuple(st_cls.DISABLED_TRIGGERS)!r}",
        "    MODEL_ENTRY_FAMILY = \"reversion\"  # the reversion exits and regime gate apply to model entries",
        f"    FAMILY_EXIT_OVERRIDES = {dict(st_cls.FAMILY_EXITS)!r}",
        f"    REVERSION_REGIME_GATE = {dict(st_cls.REVERSION_REGIME_GATE)!r}",
        "    stoploss_grace_hours = DecimalParameter(0.0, 48.0, default=24.0, decimals=1, space=\"sell\",",
        "                                            load=True, optimize=False)",
        f"    buy_params = {{**{base_cls.__name__}.buy_params, **{guards!r}}}",
        f"    sell_params = {{**{base_cls.__name__}.sell_params, **{dict(st_cls.sell_params)!r}}}",
    ]
    return "\n".join(lines).replace("{", "{{").replace("}", "}}") + "\n"


def followups() -> dict:
    """The three follow-ups (preregistration_followups.json), on the framework stage's model:
    _GATE_G24 (gate + 24 h grace), _REVX (st_g24_rev's framework, trigger entry only: the identity
    twin of st_g24_rev) and _REVG (the same framework, model AND the trigger). The Ridge excursion
    H=32 arm is a hand-written class (NNPredict_Ridge_Exc32_OP); only its plan is written here."""
    import importlib

    tag, base = selected()
    gate = f"{base}_GATE"
    out = {"selected": tag, "base": base, "arms": {}}
    what, imports, body = FRAMEWORK["G24"]
    _write_class(f"{gate}_G24", gate, "follow-up", "the gbb gate AND 24 h stoploss grace", imports,
                 body.replace("{base}", "{base}"))
    _plan(tag, f"{tag}_gate_g24", f"{gate}_G24", "039 follow-up 1: gbb gate + 24 h grace")
    out["arms"][f"{tag}_gate_g24"] = f"{gate}_G24"

    mod = REV_REFERENCE[1]
    st_cls = getattr(importlib.import_module(mod), mod.rsplit(".", 1)[1])
    base_cls = getattr(importlib.import_module(base), base)
    fw = _st_framework(base_cls, st_cls)
    imports = "from freqtrade.strategy import DecimalParameter\n"
    for suffix, mode, what in (("REVX", "triggers", "st_g24_rev's framework, trigger entry only (identity twin)"),
                               ("REVG", "trigger_and_model", "st_g24_rev's framework, model AND the gbb trigger")):
        name = f"{base}_{suffix}"
        _write_class(name, base, "follow-up", what, imports, f"    ENTRY_MODE = \"{mode}\"\n" + fw)
        _plan(tag, f"{tag}_{suffix.lower()}", name, f"039 follow-up 2: {what}")
        out["arms"][f"{tag}_{suffix.lower()}"] = name
    _plan("nnp_ridge_exc_op", "nnp_ridge_exc32_op", "NNPredict_Ridge_Exc32_OP",
          "039 follow-up 3: Ridge, excursion target at HORIZON 32 (8 h)")
    out["arms"]["nnp_ridge_exc32_op"] = "NNPredict_Ridge_Exc32_OP"
    k0 = _key(base)
    bad = {a: c for a, c in out["arms"].items() if a != "nnp_ridge_exc32_op" and _key(c) != k0}
    if bad:
        raise SystemExit(f"REFUSED: arms that would not reuse {base}'s weights: {bad}")
    print(json.dumps(out, indent=1))
    return out


def main(argv=None) -> int:
    stage = (argv or sys.argv[1:] or [""])[0]
    if stage == "framework":
        framework()
    elif stage == "sizer":
        sizer()
    elif stage == "followups":
        followups()
    else:
        raise SystemExit("usage: build_arms framework|sizer|followups")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
