"""Arm D's real NNNC path with the registry trigger as the entry -- feature 023's equivalence arm.

FR-008: "an NNNC arm whose model accepts every trigger bar MUST produce the same trade set as its
SimpleTrigger twin." This is that arm. Everything is `NNNC_A_Raw_Open` -- the same classes, the
same `NNNC_TriggerGate.json` (a copy of `NNNC_A_Raw_Open.json`, only `strategy_name` changed), the
same feature population including `BaseNNStrategy.add_additional_indicators`, the same model
loaded and run -- except that `get_entry_conditions` DISCARDS the model's opinion and returns the
`gbb` trigger instead. If its trades equal `SimpleTrigger_Gbb`'s fold for fold, the two families
share a framework and the model is the only thing arm D adds. If they differ, the difference is a
parity defect, located by diffing framework fingerprints, entry-condition counts and the first
divergent trade (023 T041).

BORROWED WEIGHTS, NEVER TRAINED. Per-fold classes `NNNC_TGT_fNN` (generated by run_folds from a
`foldplan derive --model-source NNNC_ARO` plan) load arm D's own fold model `NNNC_ARO_fNN`.
`get_model_path` keys off the class name in the base, so without the redirect a fold class would
find no model and TRAIN one inside its own backtest. `train_model` is overridden to raise, so a
missing model is a loud failure, never a silent retrain. The main feature scaler is shared at
`get_storage_location()`, exactly as arm D used it.

STOP INVARIANTS (FR-017) wrap the stop here too: the mixin returns the parent's value unchanged.
"""

import re
import sys
from pathlib import Path

import pandas as pd


sys.path.append(str(Path(__file__).parent))
sys.path.append(str(Path(__file__).parent.parent))

from NNNC_A_Raw_Open import NNNC_A_Raw_Open
from utils.StopInvariants import StopInvariantMixin


_FOLD = re.compile(r"_(f\d{2})$")


class NNNC_TriggerGate(StopInvariantMixin, NNNC_A_Raw_Open):
    TRIGGER_NAME = "gbb"
    MODEL_SOURCE = "NNNC_ARO"

    def get_model_path(self) -> str:
        m = _FOLD.search(self.__class__.__name__)
        if not m:
            raise ValueError(
                f"{self.__class__.__name__}: NNNC_TriggerGate runs only as a per-fold "
                f"class (`*_fNN`) that borrows {self.MODEL_SOURCE}_fNN's weights"
            )
        src = f"{self.MODEL_SOURCE}_{m.group(1)}"
        d = Path(self.get_storage_location()) / src
        if not d.is_dir():
            raise FileNotFoundError(f"borrowed model dir {d} is missing -- refusing to train")
        return str(d / f"{src}.keras")

    def train_model(self, *args, **kwargs):
        raise RuntimeError("NNNC_TriggerGate must never train")

    def get_entry_conditions(self, dataframe):
        # super() runs the model and writes predict_* columns, which the diagnostics read; the
        # opinion itself is discarded.
        super().get_entry_conditions(dataframe)
        from research.outcomes import triggers as _triggers

        _triggers.ensure_builtins()
        return pd.Series(
            _triggers.evaluate(self.TRIGGER_NAME, dataframe).to_numpy(), index=dataframe.index
        )
