"""Arm D's real NNNC path with the registry trigger as the entry -- feature 023's equivalence arm.

FR-008: "an NNNC arm whose model accepts every trigger bar MUST produce the same trade set as its
SimpleTrigger twin." This is that arm. Everything is `NNNC_A_Raw_Open` -- the same classes, the
same `NNNC_TriggerGate.json` (a copy of `NNNC_A_Raw_Open.json`, only `strategy_name` changed), the
same feature population including `BaseNNStrategy.add_additional_indicators`, the same model
loaded and run -- except that `get_entry_conditions` DISCARDS the model's opinion and returns the
`gbb` trigger instead. If its trades equal `SimpleTrigger_Gbb`'s fold for fold, the two families
share a framework and the model is the only thing arm D adds. If they differ, the difference is a
parity defect, located by diffing framework fingerprints, entry-condition counts and the first
divergent trade (023 T041).

ARM D'S WEIGHTS, NEVER TRAINED. Per-fold classes `NNNC_TGT_fNN` (generated by run_folds from a
`foldplan derive --model-source NNNC_ARO` plan) load arm D's own fold model `NNNC_ARO_fNN`: since
030 weights are found by MODEL KEY, and this class differs from arm D only after the model, so it
resolves to the same key. Walk-forward evaluation is strict, so a missing model is a loud failure,
never a silent retrain. The main feature scaler is shared at `get_storage_location()`, exactly as
arm D used it.

STOP INVARIANTS (FR-017) wrap the stop here too, now inherited from NNNCStrategy's shared entry
framework (029; listing the mixin here again would make the MRO impossible). The trigger is `TWIN_TRIGGER`, not `TRIGGER_NAME`:
in the shared framework a declared trigger on a model-mode strategy is refused as ambiguous, and
this class does not gate the model -- it REPLACES the model's opinion.
"""

import sys
from pathlib import Path

import pandas as pd


sys.path.append(str(Path(__file__).parent))
sys.path.append(str(Path(__file__).parent.parent))

from NNNC_A_Raw_Open import NNNC_A_Raw_Open


class NNNC_TriggerGate(NNNC_A_Raw_Open):
    TWIN_TRIGGER = "gbb"
    # Weights: `NNNC_ARO_fNN`, found by model key (030; was BorrowedModelMixin's MODEL_SOURCE).

    def get_entry_conditions(self, dataframe):
        # super() runs the model and writes predict_* columns, which the diagnostics read; the
        # opinion itself is discarded -- and so are the model-entry tags the shared framework
        # wrote for it (029): this arm's entries are the trigger's, untagged as before.
        super().get_entry_conditions(dataframe)
        self._st_tags = None
        from research.outcomes import triggers as _triggers

        _triggers.ensure_builtins()
        return pd.Series(
            _triggers.evaluate(self.TWIN_TRIGGER, dataframe).to_numpy(), index=dataframe.index
        )
